/**
 * Setting ids and credential ids from the OMP fork's registry source: `config/all-settings.ts`
 * imports every domain module, each setting is one `register({ id: "…" })` call, and a credential
 * carries `credential: true` or `ui: { secret: true }` (`Setting.isCredential`).
 */

/** The module listing every settings domain, at the fork tag. */
export const OMP_ALL_SETTINGS_PATH = "packages/coding-agent/src/config/all-settings.ts";
/** The generated module, relative to this package. */
export const SETTING_KEYS_MODULE_PATH = "src/ompSettingKeys.generated.ts";

export interface OmpSettingKeys {
  readonly settings: ReadonlyArray<string>;
  readonly credentials: ReadonlyArray<string>;
}

/** Repository paths of the domain modules `all-settings.ts` imports. */
export function settingsModulePaths(allSettingsSource: string): ReadonlyArray<string> {
  const dir = OMP_ALL_SETTINGS_PATH.slice(0, OMP_ALL_SETTINGS_PATH.lastIndexOf("/"));
  const paths = new Set<string>();
  for (const match of allSettingsSource.matchAll(/from\s+"(\.{1,2}\/[^"]+)"/g)) {
    const segments = dir.split("/");
    for (const part of (match[1] ?? "").split("/")) {
      if (part === "..") segments.pop();
      else if (part !== ".") segments.push(part);
    }
    paths.add(`${segments.join("/")}.ts`);
  }
  return [...paths];
}

/** Every registered setting id and the credential ids among them, sorted. */
export function extractOmpSettingKeys(moduleSources: ReadonlyArray<string>): OmpSettingKeys {
  const settings = new Set<string>();
  const credentials = new Set<string>();
  for (const source of moduleSources) {
    // Each chunk runs from one `register(` call to the next.
    for (const chunk of source.split("register(").slice(1)) {
      const id = /\bid:\s*"([^"]+)"/.exec(chunk)?.[1];
      if (id === undefined) continue;
      settings.add(id);
      if (/\b(?:credential|secret):\s*true\b/.test(chunk)) credentials.add(id);
    }
  }
  const sorted = (ids: Set<string>) => [...ids].toSorted();
  return { settings: sorted(settings), credentials: sorted(credentials) };
}

export function renderOmpSettingKeysModule(
  keys: OmpSettingKeys,
  source: { readonly repository: string; readonly tag: string; readonly commit: string },
): string {
  const list = (ids: ReadonlyArray<string>) => ids.map((id) => `  "${id}",\n`).join("");
  return [
    `// Generated by \`contract:vendor\` from ${source.repository}@${source.tag} (${source.commit}). Do not edit.\n`,
    "// `contract:check` fails when the pinned tag's settings registry differs.\n",
    "\n",
    "/** Every setting the pinned OMP registers. */\n",
    "export const OMP_SETTING_KEYS: ReadonlyArray<string> = [\n",
    list(keys.settings),
    "];\n",
    "\n",
    "/** Settings the pinned OMP marks as credentials (`credential: true` or `ui.secret`). */\n",
    "export const OMP_CREDENTIAL_SETTING_KEYS: ReadonlyArray<string> = [\n",
    list(keys.credentials),
    "];\n",
  ].join("");
}
