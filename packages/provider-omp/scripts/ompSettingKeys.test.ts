import { describe, expect, it } from "vite-plus/test";

import {
  extractOmpSettingKeys,
  renderOmpSettingKeysModule,
  settingsModulePaths,
} from "./ompSettingKeys.ts";

describe("OMP settings registry extraction", () => {
  it("resolves the domain modules all-settings.ts imports", () => {
    const source = [
      'import { all, type AnySetting, Setting } from "./registry";',
      'import * as modesSettings from "../modes/settings";',
      'import * as webSettings from "../web/settings";',
      'import { logger } from "@oh-my-pi/pi-utils";',
    ].join("\n");
    expect(settingsModulePaths(source)).toEqual([
      "packages/coding-agent/src/config/registry.ts",
      "packages/coding-agent/src/modes/settings.ts",
      "packages/coding-agent/src/web/settings.ts",
    ]);
  });

  it("reads ids and both credential markers from register calls", () => {
    const web = `
export const cfgSearxngToken = register({
	id: "searxng.token",
	type: "string",
	default: undefined,
	credential: true,
});
export const cfgSearxngUser = register({ id: "searxng.basicUsername", type: "string" });
export const cfgKey = register({
	id: "x.apiKey",
	type: "string",
	ui: { tab: "web", description: "Key", secret: true },
});
export function register(definition) { return definition; }`;
    expect(extractOmpSettingKeys([web])).toEqual({
      settings: ["searxng.basicUsername", "searxng.token", "x.apiKey"],
      credentials: ["searxng.token", "x.apiKey"],
    });
  });

  it("renders a stable module", () => {
    const rendered = renderOmpSettingKeysModule(
      { settings: ["a", "b"], credentials: ["b"] },
      { repository: "o/r", tag: "v1", commit: "abc" },
    );
    expect(rendered).toContain(
      'export const OMP_CREDENTIAL_SETTING_KEYS: ReadonlyArray<string> = [\n  "b",\n];\n',
    );
    expect(rendered.startsWith("// Generated by `contract:vendor` from o/r@v1 (abc).")).toBe(true);
  });
});
